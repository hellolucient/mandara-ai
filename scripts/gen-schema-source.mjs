// Embeds every migrations/*.sql file into src/lib/schema-source.ts.
// Cloudflare Workers have no filesystem, so the runtime and the deploy-time migrator read the schema from code.
// Runs before every build; `npm run schema` regenerates it by hand. Commit the result.
import { readdir, readFile, writeFile } from "node:fs/promises";

const names = (await readdir("migrations")).filter((file) => file.endsWith(".sql")).sort();
const entries = await Promise.all(
  names.map(async (name) => ({ name, sql: (await readFile(`migrations/${name}`, "utf8")).trim() })),
);
const body = `// Generated by scripts/gen-schema-source.mjs from migrations/*.sql. Do not edit by hand.
export function splitSql(sql: string): string[] {
  return sql
    .split(";")
    .map((part) => part.trim())
    .filter((part) => part.length > 0);
}

export const SCHEMA_MIGRATIONS: Array<{ name: string; sql: string }> = [
${entries.map((e) => `  {\n    name: ${JSON.stringify(e.name)},\n    sql: ${JSON.stringify(e.sql)},\n  },`).join("\n")}
];
`;
await writeFile("src/lib/schema-source.ts", body);
console.log(`schema-source: ${entries.length} migrations embedded`);
